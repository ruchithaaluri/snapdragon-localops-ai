"""The diagnosis view: ranked hypotheses, each with the evidence it cites.

Two things are always on screen, because they are the difference between a
diagnosis and a guess: how the answer was *reasoned about* (``rules_only`` or a
model), and the *provenance* of the run that produced it. A confidence number
without those is decoration.
"""

from __future__ import annotations

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QGroupBox,
    QHBoxLayout,
    QLabel,
    QTextBrowser,
    QVBoxLayout,
    QWidget,
)

from core.contracts.diagnostics import Diagnosis
from app.ui.theme import Theme
from app.ui.widgets import StatusPill

__all__ = ["DiagnosisPanel"]


class DiagnosisPanel(QWidget):
    """Renders one :class:`Diagnosis`."""

    def __init__(self, theme: Theme, parent=None) -> None:  # noqa: ANN001 - Qt parent
        super().__init__(parent)
        self._theme = theme
        layout = QVBoxLayout(self)
        layout.setContentsMargins(8, 8, 8, 8)
        layout.setSpacing(8)

        header = QGroupBox("Conclusion")
        header_layout = QVBoxLayout(header)
        self._summary = QLabel("Run an analysis to see a diagnosis.")
        self._summary.setWordWrap(True)
        header_layout.addWidget(self._summary)

        meta = QHBoxLayout()
        self._mode_pill = StatusPill(theme)
        self._confidence = QLabel()
        self._execution = QLabel()
        self._execution.setWordWrap(True)
        meta.addWidget(self._mode_pill)
        meta.addWidget(self._confidence)
        meta.addWidget(self._execution, 1)
        header_layout.addLayout(meta)
        layout.addWidget(header)

        self._hypotheses = QTextBrowser()
        self._hypotheses.setOpenExternalLinks(False)
        layout.addWidget(self._hypotheses, 1)

    # -- rendering --------------------------------------------------------

    def clear(self, message: str = "Run an analysis to see a diagnosis.") -> None:
        self._summary.setText(message)
        self._mode_pill.set_status("no result", "muted")
        self._confidence.setText("")
        self._execution.setText("")
        self._hypotheses.clear()

    def show_diagnosis(self, diagnosis: Diagnosis | None) -> None:
        """Render a diagnosis, or explain why there is none."""
        if diagnosis is None:
            self.clear(
                "No diagnosis was produced. The engine refused to name a cause "
                "because the evidence did not support one - add more of the error "
                "output and try again."
            )
            return

        self._summary.setText(diagnosis.summary)

        mode = diagnosis.reasoning_mode.value
        self._mode_pill.set_status(
            "rules only (no model)" if mode == "rules_only" else f"model: {mode}",
            "info" if mode == "rules_only" else "ok",
            "Pattern matching is not inference. No language model produced this answer."
            if mode == "rules_only"
            else "A local model reasoned over the evidence.",
        )
        self._confidence.setText(f"confidence {diagnosis.confidence:.2f}")
        self._execution.setText(
            f"Executed on: {diagnosis.provenance.execution.describe()}"
            if diagnosis.provenance
            else "Execution target not recorded"
        )

        parts: list[str] = [self._provenance_block(diagnosis), "", "<h3>Hypotheses, strongest first</h3>"]
        for hypothesis in diagnosis.ranked():
            parts.append(self._hypothesis_block(hypothesis))

        if diagnosis.gaps:
            parts += ["", "<h3>Caveats</h3>", "<ul>"]
            parts += [f"<li>{_escape(gap)}</li>" for gap in diagnosis.gaps]
            parts.append("</ul>")

        self._hypotheses.setHtml("".join(parts))

    # -- helpers ----------------------------------------------------------

    def _provenance_block(self, diagnosis: Diagnosis) -> str:
        provenance = diagnosis.provenance
        target = (
            provenance.execution.describe() if provenance else "not recorded"
        )
        reasoning = diagnosis.reasoning_mode.value
        note = (
            "<p><i>Pattern matching is not inference. This answer was derived "
            "from the cited evidence, not generated by a model.</i></p>"
            if reasoning == "rules_only"
            else ""
        )
        return (
            f"<p><b>Reasoning:</b> {reasoning} &nbsp;|&nbsp; "
            f"<b>Confidence:</b> {diagnosis.confidence:.2f} &nbsp;|&nbsp; "
            f"<b>Executed on:</b> {_escape(target)}</p>{note}"
        )

    @staticmethod
    def _hypothesis_block(hypothesis) -> str:  # noqa: ANN001 - Hypothesis
        cites = ", ".join(hypothesis.evidence_ids[:8])
        if len(hypothesis.evidence_ids) > 8:
            cites += f" (+{len(hypothesis.evidence_ids) - 8} more)"
        rationale = f"<p>{_escape(hypothesis.rationale)}</p>" if hypothesis.rationale else ""
        return (
            f"<p><b>{_escape(hypothesis.statement)}</b><br>"
            f"status: {hypothesis.status.value} &middot; "
            f"confidence: {hypothesis.confidence:.2f}</p>"
            f"{rationale}"
            f"<p style='color: #888'><small>cites: {_escape(cites)}</small></p>"
            "<hr>"
        )


def _escape(text: str) -> str:
    """Escape text for the rich-text views.

    Evidence and log lines are arbitrary text; pasting ``<`` into an HTML view
    would otherwise be interpreted as markup.
    """
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )
